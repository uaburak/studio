/** Turkish label of a Vision identifier; the identifier in plain words when there is none. */
export function turkishLabel(identifier: string): string {
  return TR[identifier] ?? identifier.replace(/_/g, " ");
}

export function hasTurkishLabel(identifier: string): boolean {
  return identifier in TR;
}

/**
 * Turkish colour names for the library's colour chips and search (hue / lightness buckets).
 */
export function colorName(r: number, g: number, b: number): string {
  const max = Math.max(r, g, b) / 255;
  const min = Math.min(r, g, b) / 255;
  const l = (max + min) / 2;
  const d = max - min;
  const s = d === 0 ? 0 : d / (1 - Math.abs(2 * l - 1));
  if (l < 0.13) return "siyah";
  if (l > 0.92 && s < 0.35) return "beyaz";
  if (s < 0.14) return l < 0.35 ? "koyu gri" : l > 0.75 ? "açık gri" : "gri";
  let h = 0;
  const rn = r / 255;
  const gn = g / 255;
  const bn = b / 255;
  if (d !== 0) {
    if (max === rn) h = ((gn - bn) / d) % 6;
    else if (max === gn) h = (bn - rn) / d + 2;
    else h = (rn - gn) / d + 4;
    h *= 60;
    if (h < 0) h += 360;
  }
  if (h >= 12 && h < 45 && l < 0.45) return "kahverengi";
  if (h < 12 || h >= 345) return l > 0.75 ? "pembe" : "kırmızı";
  if (h < 40) return l > 0.78 ? "bej" : "turuncu";
  if (h < 70) return l < 0.4 ? "zeytin yeşili" : "sarı";
  if (h < 160) return "yeşil";
  if (h < 195) return "turkuaz";
  if (h < 250) return l < 0.3 ? "lacivert" : "mavi";
  if (h < 290) return "mor";
  return l > 0.7 ? "pembe" : "mor";
}

/** Shape of src/renderer/design/tokens.json (exported from the Wecra Foundations). */
export interface TokenDoc {
  primitives: Record<string, string>;
  theme: Record<string, { dark: string; light: string }>;
  spacing: Record<string, number>;
  radius: Record<string, number>;
  text: Record<
    string,
    { size: number; line: number; weight: number; tracking?: number; family?: "mono" }
  >;
  effects: Record<string, ShadowLayer[] | { shadow: ShadowLayer[]; backdropBlur: number }>;
  motion: Record<string, string>;
}

export interface ShadowLayer {
  x?: number;
  y: number;
  blur: number;
  spread?: number;
  color: string;
}

/** `gray/810` → `gray-810`; `$`-prefixed keys are comments. */
export function varName(token: string): string {
  return token.replace(/\//g, "-").toLowerCase();
}

export function shadowCss(layers: ShadowLayer[]): string {
  return layers
    .map((l) => `${l.x ?? 0}px ${l.y}px ${l.blur}px ${l.spread ?? 0}px ${l.color.toLowerCase()}`)
    .join(", ");
}

function entries<T>(record: Record<string, T>): [string, T][] {
  return Object.entries(record).filter(([key]) => !key.startsWith("$"));
}

function themeBlock(doc: TokenDoc, mode: "dark" | "light", indent: string): string {
  return entries(doc.theme)
    .map(([name, modes]) => `${indent}--${varName(name)}: var(--${varName(modes[mode])});`)
    .join("\n");
}

/** The CSS custom properties: primitives, sizes, text, effects, motion and both themes. */
export function renderTokensCss(doc: TokenDoc): string {
  const lines: string[] = [];
  lines.push("/* Generated by scripts/gen-tokens.ts from design/tokens.json. Do not edit. */");
  lines.push(":root {");
  for (const [name, value] of entries(doc.primitives)) {
    lines.push(`  --${varName(name)}: ${value.toLowerCase()};`);
  }
  for (const [name, value] of entries(doc.spacing)) lines.push(`  --${varName(name)}: ${value}px;`);
  for (const [name, value] of entries(doc.radius)) lines.push(`  --${varName(name)}: ${value}px;`);
  for (const [name, style] of entries(doc.text)) {
    lines.push(`  --type-${name}-size: ${style.size}px;`);
    lines.push(`  --type-${name}-line: ${style.line}px;`);
    lines.push(`  --type-${name}-weight: ${style.weight};`);
    lines.push(`  --type-${name}-tracking: ${style.tracking ?? 0}px;`);
  }
  for (const [name, effect] of entries(doc.effects)) {
    if (Array.isArray(effect)) {
      lines.push(`  --${varName(name)}: ${shadowCss(effect)};`);
    } else {
      lines.push(`  --${varName(name)}-shadow: ${shadowCss(effect.shadow)};`);
      lines.push(`  --${varName(name)}-blur: ${effect.backdropBlur}px;`);
    }
  }
  for (const [name, value] of entries(doc.motion)) lines.push(`  --${varName(name)}: ${value};`);
  lines.push("");
  lines.push("  /* Light */");
  lines.push("  color-scheme: light;");
  lines.push(themeBlock(doc, "light", "  "));
  lines.push("}");
  lines.push("");
  lines.push("/* Dark: follows the system unless the app forces light (Ayarlar → Görünüm). */");
  lines.push("@media (prefers-color-scheme: dark) {");
  lines.push('  :root:not([data-theme="light"]) {');
  lines.push("    color-scheme: dark;");
  lines.push(themeBlock(doc, "dark", "    "));
  lines.push("  }");
  lines.push("}");
  lines.push("");
  lines.push(':root[data-theme="dark"] {');
  lines.push("  color-scheme: dark;");
  lines.push(themeBlock(doc, "dark", "  "));
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}
